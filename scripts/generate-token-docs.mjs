#!/usr/bin/env node
/**
 * Token reference generator.
 *
 * Reads the published `@qavo/theming` ESM bundle from `dist/qavo-theming/`
 * and renders `docs/token-reference.md`: one section per token category, each
 * a Markdown table that joins the typed catalog (`TOKEN_CATALOG`) with the
 * runtime values of the built-in light and dark themes, plus the responsive
 * breakpoints.
 *
 * Run via `npm run docs:tokens`, which builds the library first so the
 * script always operates on the same artifacts npm publishes.
 *
 * The catalog is the source of truth for token *intent* (purpose, classification).
 * The theme files are the source of truth for token *values*. By generating
 * the table mechanically we guarantee documentation stays in lock-step with
 * the contract: rename a token without updating the catalog and the TypeScript
 * compiler fails; add a token without documenting it and the table column for
 * the new field shows up as `—`, surfacing the omission in code review.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

// Loading the FESM ESM pulls Angular decorated services (e.g. `DOCUMENT`) which
// the partial-compilation output expects to be JIT-linked at runtime. Pulling
// in `@angular/compiler` before any Angular code runs satisfies that contract.
await import('@angular/compiler');

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..');
const themingPackage = join(repoRoot, 'dist', 'qavo-theming');
const outputPath = join(repoRoot, 'docs', 'token-reference.md');

async function loadThemingModule() {
  const pkgJsonPath = join(themingPackage, 'package.json');
  let pkg;
  try {
    pkg = JSON.parse(readFileSync(pkgJsonPath, 'utf8'));
  } catch (err) {
    console.error(
      `Could not read ${pkgJsonPath}. Did you run \`npm run build qavo-theming\` first?`,
    );
    throw err;
  }
  // ng-packagr emits `module` (fesm2022) plus `exports[ "." ].default`.
  const entry =
    pkg.exports?.['.']?.default ??
    pkg.exports?.['.']?.import ??
    pkg.module ??
    pkg.main;
  if (!entry) {
    throw new Error('No usable entry point found in dist/qavo-theming/package.json.');
  }
  return import(pathToFileURL(join(themingPackage, entry)).href);
}

function escapeCell(value) {
  return String(value).replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function kebab(value) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([0-9])([a-zA-Z])/g, '$1-$2')
    .toLowerCase();
}

function cssVariable(category, name) {
  return `--qavo-${kebab(category)}-${kebab(name)}`;
}

function classificationBadge(classification, themeDependent) {
  const themed = themeDependent ? ' · theme-dependent' : '';
  return `${classification}${themed}`;
}

function renderCategory(category, docs, lightTokens, darkTokens) {
  const rows = Object.entries(docs).map(([name, doc]) => {
    const variable = cssVariable(category, name);
    const lightValue = lightTokens?.[category]?.[name] ?? '—';
    const darkValue = darkTokens?.[category]?.[name] ?? '—';
    return `| \`${variable}\` | ${escapeCell(doc.purpose)} | ${escapeCell(lightValue)} | ${escapeCell(darkValue)} | ${classificationBadge(doc.classification, doc.themeDependent)} |`;
  });
  return [
    `### \`${category}\``,
    '',
    '| CSS variable | Purpose | Light default | Dark default | Classification |',
    '| --- | --- | --- | --- | --- |',
    ...rows,
    '',
  ].join('\n');
}

function renderBreakpoints(docs, breakpoints) {
  const rows = Object.entries(docs).map(([name, doc]) => {
    const value = breakpoints?.[name];
    const display = typeof value === 'number' ? `${value}px` : value ?? '—';
    return `| \`--qavo-breakpoint-${kebab(name)}\` | ${escapeCell(doc.purpose)} | ${escapeCell(display)} | ${classificationBadge(doc.classification, doc.themeDependent)} |`;
  });
  return [
    '### `breakpoint`',
    '',
    '| CSS variable | Purpose | Value | Classification |',
    '| --- | --- | --- | --- |',
    ...rows,
    '',
  ].join('\n');
}

function header() {
  const stamp = new Date().toISOString().slice(0, 10);
  return [
    '# Qavo Token Reference',
    '',
    '> Auto-generated by `scripts/generate-token-docs.mjs` — do **not** edit by hand.',
    `> Last regenerated: ${stamp}.`,
    '',
    'This page is the public contract for every design token Qavo exposes as a',
    'CSS custom property. Application themes may override any token; component',
    'libraries (`@qavo/ui` and downstream plugins) reference these variables',
    'and never raw values, so an override flows through to every consumer with',
    'no rebuild.',
    '',
    '**SemVer policy.** Adding a token is a MINOR change. Renaming or removing a',
    'token is a MAJOR change; the changelog will call out the new name and a',
    'short migration note. The two built-in themes (`light`, `dark`) define a',
    'value for every token and are validated in CI.',
    '',
    '## Categories',
    '',
  ].join('\n');
}

async function main() {
  const mod = await loadThemingModule();
  const { TOKEN_CATALOG, BREAKPOINT_DOCS, LIGHT_THEME, DARK_THEME, BREAKPOINT_TOKENS } = mod;
  if (!TOKEN_CATALOG || !LIGHT_THEME || !DARK_THEME) {
    throw new Error(
      'Built `@qavo/theming` is missing one or more expected exports ' +
        '(`TOKEN_CATALOG`, `LIGHT_THEME`, `DARK_THEME`). Has the public-api drifted?',
    );
  }

  const lightTokens = LIGHT_THEME.tokens;
  const darkTokens = DARK_THEME.tokens;

  const sections = [
    header(),
    ...Object.entries(TOKEN_CATALOG).map(([category, docs]) =>
      renderCategory(category, docs, lightTokens, darkTokens),
    ),
    renderBreakpoints(BREAKPOINT_DOCS, BREAKPOINT_TOKENS),
  ];

  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, sections.join('\n'), 'utf8');
  console.log(`Wrote ${outputPath}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
